/**
 * Class that extends the Phoenix 6 SwerveDrivetrain class and implements
 * Subsystem so it can easily be used in command-based projects.
 * <p>
 * Generated by the 2026 Tuner X Swerve Project Generator
 * https://v6.docs.ctr-electronics.com/en/stable/docs/tuner/tuner-swerve/index.html
 */
public class ChassisSubsystem extends TunerSwerveDrivetrain implements Subsystem {
    private static final double MAX_TRANSLATION_SPEED = TunerConstants.kSpeedAt12Volts.in(MetersPerSecond); // kSpeedAt12Volts desired top speed
    private static final double MAX_ROTATION_RATE = RotationsPerSecond.of(0.75).in(RadiansPerSecond); // 3/4 of a rotation per second max angular velocity

    private static final double SIM_LOOP_PERIOD = 0.004; // 4 ms
    private Notifier m_simNotifier;
    private double m_lastSimTime;

    /* Blue alliance sees forward as 0 degrees (toward red alliance wall) */
    private static final Rotation2d BLUE_ALLIANCE_PERSPECTIVE_ROTATION = Rotation2d.ZERO;
    /* Red alliance sees forward as 180 degrees (toward blue alliance wall) */
    private static final Rotation2d RED_ALLIANCE_PERSPECTIVE_ROTATION = Rotation2d.PI;
    /* Keep track if we've ever applied the operator perspective before or not */
    private boolean m_hasAppliedOperatorPerspective;

    private final SwerveRequest.ApplyRobotVelocity m_pathApplyRobotSpeeds = new SwerveRequest.ApplyRobotVelocity();

    private final SwerveRequest.FieldCentric m_fieldCentricDriveRequest = new SwerveRequest.FieldCentric()
        .withDeadband(MAX_TRANSLATION_SPEED * 0.1).withRotationalDeadband(MAX_ROTATION_RATE * 0.1) // Add a 10% deadband
        .withDriveRequestType(DriveRequestType.OpenLoopVoltage); // Use open-loop control for drive motors

    private final SwerveRequest.RobotCentric m_robotCentricDriveRequest = new SwerveRequest.RobotCentric()
        .withDeadband(MAX_TRANSLATION_SPEED * 0.1).withRotationalDeadband(MAX_ROTATION_RATE * 0.1)
        .withDriveRequestType(DriveRequestType.OpenLoopVoltage);

    private final CANrange m_canRange = new CANrange(Constants.CAN_RANGE_ID, new CANBus());
    private final GosDoubleProperty m_distanceToWall = new GosDoubleProperty(Constants.DEFAULT_CONSTANT_PROPERTIES, "Distance to Wall", 2);
    private final TunablePathConstraints m_pathConstraints = new TunablePathConstraints(Constants.DEFAULT_CONSTANT_PROPERTIES, "Path Constraints", 60, 60, 180, 180);

    private final GosField m_gosField = new GosField();


    /**
     * Constructs a CTRE SwerveDrivetrain using the specified constants.
     * <p>
     * This constructs the underlying hardware devices, so users should not construct
     * the devices themselves. If they need the devices, they can access them through
     * getters in the classes.
     *
     * @param drivetrainConstants Drivetrain-wide constants for the swerve drive
     * @param modules             Constants for each specific module
     */
    public ChassisSubsystem(
        SwerveDrivetrainConstants drivetrainConstants,
        SwerveModuleConstants<?, ?, ?>... modules
    ) {
        super(drivetrainConstants, modules);
        if (Utils.isSimulation()) {
            startSimThread();
        }
        configureAutoBuilder();
        PathPlannerLogging.setLogActivePathCallback(m_gosField::setTrajectory);
        PathPlannerLogging.setLogTargetPoseCallback(m_gosField::setTrajectorySetpoint);

    }

    @SuppressWarnings("PMD")
    private void configureAutoBuilder() {
        try {
            var config = RobotConfig.fromGUISettings();
            AutoBuilder.configure(
                () -> getState().Pose,   // Supplier of current robot pose
                this::resetPose,         // Consumer for seeding pose against auto
                () -> getState().Velocity, // Supplier of current robot speeds
                // Consumer of ChassisVelocities and feedforwards to drive the robot
                (speeds, feedforwards) -> setControl(
                    m_pathApplyRobotSpeeds.withVelocity(speeds.discretize(0.020))
                        .withWheelForceFeedforwardsX(feedforwards.robotRelativeForcesXNewtons())
                        .withWheelForceFeedforwardsY(feedforwards.robotRelativeForcesYNewtons())
                ),
                new PPHolonomicDriveController(
                    // PID constants for translation
                    new PIDConstants(10, 0, 0),
                    // PID constants for rotation
                    new PIDConstants(7, 0, 0)
                ),
                config,
                // Assume the path needs to be flipped for Red vs Blue, this is normally the case
                () -> MatchState.getAlliance().orElse(Alliance.BLUE) == Alliance.RED,
                this // Subsystem for requirements
            );
        } catch (Exception ex) {
            DriverStationErrors.reportError("Failed to load PathPlanner config and configure AutoBuilder", ex.getStackTrace());
        }
    }

    public Command createPathOnTheFly(MaybeFlippedPose2d goal) {
        return defer(() -> createPathOnTheFlyNotUpdated(goal));
    }

    public Command createPathOnTheFlyNotUpdated(MaybeFlippedPose2d goal) {
        // Create a list of waypoints from poses. Each pose represents one waypoint.
        // The rotation component of the pose should be the direction of travel. Do not use holonomic rotation.

        List<Waypoint> waypoints = PathPlannerPath.waypointsFromPoses(
                getState().Pose, //current position
                goal.getPose()
        );


        PathConstraints constraints = m_pathConstraints.getConstraints();

        // Create the path using the waypoints created above
        PathPlannerPath path = new PathPlannerPath(
                waypoints,
                constraints,
                null, // The ideal starting state, this is only relevant for pre-planned paths, so can be null for on-the-fly paths.
                new GoalEndState(0.0, goal.getPose().getRotation()) // Goal end state. You can set a holonomic rotation here. If using a differential drivetrain, the rotation will have no effect.
        );

        // Prevent the path from being flipped if the coordinates are already correct
        path.preventFlipping = true;

        return AutoBuilder.followPath(path);
    }

    public void driveFieldCentric(double xJoystick, double yJoystick, double rotationalJoystick) {
        setControl(
            m_fieldCentricDriveRequest.withVelocityX(xJoystick * MAX_TRANSLATION_SPEED)
                .withVelocityY(yJoystick * MAX_TRANSLATION_SPEED)
                .withRotationalRate(rotationalJoystick * MAX_ROTATION_RATE)
        );
    }

    public void driveRobotCentric(double xJoystick, double yJoystick, double rotationalJoystick) {
        setControl(
            m_robotCentricDriveRequest.withVelocityX(xJoystick * MAX_TRANSLATION_SPEED)
                .withVelocityY(yJoystick * MAX_TRANSLATION_SPEED)
                .withRotationalRate(rotationalJoystick * MAX_ROTATION_RATE)
        );
    }

    public double getDistanceToWall() {
        return m_canRange.getDistance().getValueAsDouble();
    }

    public boolean canSeeWall() {
        return getDistanceToWall() <= m_distanceToWall.getValue();
    }

    @Override
    public void periodic() {
        Telemetry.log("Field", m_gosField.getField2d());
        /*
         * Periodically try to apply the operator perspective.
         * If we haven't applied the operator perspective before, then we should apply it regardless of DS state.
         * This allows us to correct the perspective in case the robot code restarts mid-match.
         * Otherwise, only check and apply the operator perspective if the DS is disabled.
         * This ensures driving behavior doesn't change until an explicit disable event occurs during testing.
         */
        if (!m_hasAppliedOperatorPerspective || RobotState.isDisabled()) {
            MatchState.getAlliance().ifPresent(allianceColor -> {
                setOperatorForwardDirection(
                    allianceColor == Alliance.RED
                        ? RED_ALLIANCE_PERSPECTIVE_ROTATION
                        : BLUE_ALLIANCE_PERSPECTIVE_ROTATION
                );
                m_hasAppliedOperatorPerspective = true;
            });
        }
        m_gosField.setPoseEstimate(getState().Pose);
    }

    private void startSimThread() {
        m_lastSimTime = Utils.getCurrentTimeSeconds();

        /* Run simulation at a faster rate so PID gains behave more reasonably */
        m_simNotifier = new Notifier(() -> {
            final double currentTime = Utils.getCurrentTimeSeconds();
            double deltaTime = currentTime - m_lastSimTime;
            m_lastSimTime = currentTime;

            /* use the measured time delta, get battery voltage from WPILib */
            updateSimState(deltaTime, RobotController.getBatteryVoltage());
        });
        m_simNotifier.startPeriodic(SIM_LOOP_PERIOD);
    }

    public void addChassisDebugCommands() {
        CommandTab tab = new CommandTab("Chassis");
        try {
            PathPlannerPath path = PathPlannerPath.fromChoreoTrajectory("KitchenToCenterLine");
            Command resetPose = runOnce(() -> resetPose(path.getStartingHolonomicPose().orElse(new Pose2d())));
            tab.add(resetPose.andThen(AutoBuilder.followPath(path)));

        } catch (IOException | ParseException e) {
            throw new RuntimeException(e);
        }
        // Create a path following command using AutoBuilder. This will also trigger event markers.
        tab.add(createSeedFieldCentricCommand());

        for (StartingPositions position : StartingPositions.values()) {
            tab.add(createPathOnTheFly(position.m_pose).withName("Auto Drive To/" + position.name()));
        }

    }

    public Command createSeedFieldCentricCommand() {
        return run(this::createSeedFieldCentricCommand)
            .ignoringDisable(true)
            .withName("Reset gyro");
    }
}
